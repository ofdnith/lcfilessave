const MAIN_WINDOW: &str = "main";
const MENU_CHANGE_SERVER: &str = "change-server";
const MENU_RELOAD: &str = "reload";

/// Commands the remote web UI may call. Each has an autogenerated
/// `allow-<name>` permission (see build.rs).
const REMOTE_PERMISSIONS: &[&str] = &[
    "allow-list-disks",
    "allow-init-volume",
    "allow-copy-to-volume",
    "allow-write-bundle-file",
    "allow-verify-volume-files",
    "allow-open-on-volume",
    "allow-pick-folder",
    "allow-scan-folder",
    "allow-hash-file",
    "allow-upload-file",
    "allow-get-server-url",
    // listen/unlisten for the `copy-progress` event
    "core:event:default",
];

// ---------------------------------------------------------------------------
// State
// ---------------------------------------------------------------------------

struct Shared {
    config_path: PathBuf,
    server_url: Option<String>,
    /// Origins that already got a runtime capability in this run.
    granted: HashSet<String>,
    /// URL of the bundled local page (differs between `tauri dev` and builds).
    local_url: Option<Url>,
}

#[derive(Clone)]
struct AppState {
    shared: Arc<Mutex<Shared>>,
    http: reqwest::Client,
}

impl AppState {
    fn server_url(&self) -> Option<String> {
        self.shared.lock().unwrap().server_url.clone()
    }

    /// The token is only ever sent to the configured server: a command call
    /// naming another server is refused.
    fn require_server(&self, server_url: &str) -> Result<String, String> {
        let wanted = config::normalize_server_url(server_url)?;
        match self.server_url() {
            Some(cur) if cur == wanted => Ok(cur),
            Some(_) => Err("Servidor diferente do configurado neste app.".into()),
            None => Err("Nenhum servidor configurado.".into()),
        }
    }
}

/// Grants the remote server's pages access to the native commands.
///
/// Tauri blocks IPC from remote origins unless a capability with `remote.urls`
/// matches. The server address is chosen by the user at runtime, so it cannot
/// live in `capabilities/*.json`; we add a capability at runtime instead,
/// scoped to exactly that origin (`scheme://host:port/*`) and to the main
/// window. Capabilities cannot be revoked while running, so after switching
/// servers the old origin stays allowed until the app restarts — but the
/// navigation guard below never lets the window load any origin other than
/// the configured one, so it cannot be reached.
fn grant_remote(app: &AppHandle, state: &AppState, origin: &str) -> Result<(), String> {
    let mut sh = state.shared.lock().unwrap();
    if sh.granted.contains(origin) {
        return Ok(());
    }
    let id = format!("remote-server-{}", sh.granted.len() + 1);
    let mut cap = CapabilityBuilder::new(id)
        .remote(format!("{origin}/*"))
        .local(false)
        .window(MAIN_WINDOW);
    for p in REMOTE_PERMISSIONS {
        cap = cap.permission(*p);
    }
    app.add_capability(cap)
        .map_err(|e| format!("Não consegui liberar o servidor no app: {e}"))?;
    sh.granted.insert(origin.to_string());
    Ok(())
}

fn origin_of(url: &Url) -> String {
    match url.port() {
        Some(p) => format!("{}://{}:{}", url.scheme(), url.host_str().unwrap_or(""), p),
        None => format!("{}://{}", url.scheme(), url.host_str().unwrap_or("")),
    }
}

/// Which URLs the main window may load. Everything else opens in the browser.
fn navigation_allowed(shared: &Shared, url: &Url) -> bool {
    match url.scheme() {
        "tauri" | "about" | "data" | "blob" => return true,
        _ => {}
    }
    if url.host_str() == Some("tauri.localhost") {
        return true;
    }
    if let Some(local) = &shared.local_url {
        if origin_of(local) == origin_of(url) {
            return true;
        }
    }
    matches!(&shared.server_url, Some(s) if *s == origin_of(url).to_ascii_lowercase())
}

fn go_to_local_page(app: &AppHandle, query: &str) {
    let state = app.state::<AppState>();
    let local = state.shared.lock().unwrap().local_url.clone();
    if let (Some(win), Some(mut url)) = (app.get_webview_window(MAIN_WINDOW), local) {
        url.set_query(if query.is_empty() { None } else { Some(query) });
        let _ = win.navigate(url);
    }
}

