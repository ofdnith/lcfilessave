#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .menu(build_menu)
        .on_menu_event(|app, event| match event.id().as_ref() {
            MENU_CHANGE_SERVER => go_to_local_page(app, "trocar=1"),
            MENU_RELOAD => {
                if let Some(w) = app.get_webview_window(MAIN_WINDOW) {
                    let _ = w.reload();
                }
            }
            _ => {}
        })
        .setup(|app| {
            let config_path = app.path().app_config_dir()?.join("config.json");
            let cfg = config::load(&config_path);
            let server_url = cfg
                .server_url
                .as_deref()
                .and_then(|u| config::normalize_server_url(u).ok());
            let state = AppState {
                shared: Arc::new(Mutex::new(Shared {
                    config_path,
                    server_url: server_url.clone(),
                    granted: HashSet::new(),
                    local_url: None,
                })),
                http: transfer::http_client(),
            };
            app.manage(state.clone());
            if let Some(origin) = &server_url {
                grant_remote(app.handle(), &state, origin)?;
            }

            // The window is declared in tauri.conf.json with `create: false`
            // so we can attach the navigation guard here.
            let win_cfg = app
                .config()
                .app
                .windows
                .iter()
                .find(|w| w.label == MAIN_WINDOW)
                .cloned()
                .ok_or("janela principal ausente em tauri.conf.json")?;
            let guard = state.shared.clone();
            let handle = app.handle().clone();
            let window = WebviewWindowBuilder::from_config(app.handle(), &win_cfg)?
                .on_navigation(move |url| {
                    let allowed = navigation_allowed(&guard.lock().unwrap(), url);
                    if !allowed && matches!(url.scheme(), "http" | "https" | "mailto") {
                        // Links to other sites open in the default browser.
                        let _ = handle.opener().open_url(url.as_str(), None::<&str>);
                    }
                    allowed
                })
                .build()?;
            // The bundled page decides where to go: it checks the saved server
            // and navigates there, or asks for an address.
            state.shared.lock().unwrap().local_url = window.url().ok();
            let _ = WebviewUrl::default(); // (window URL comes from config: index.html)
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            get_server_url,
            set_server_url,
            test_server,
            list_disks,
            init_volume,
            copy_to_volume,
            write_bundle_file,
            verify_volume_files,
            open_on_volume,
            pick_folder,
            scan_folder,
            hash_file,
            upload_file,
        ])
        .run(tauri::generate_context!())
        .expect("erro ao iniciar o Acervo");
}

#[cfg(test)]
mod tests {
    use super::*;

    fn shared(server: Option<&str>) -> Shared {
        Shared {
            config_path: PathBuf::new(),
            server_url: server.map(str::to_string),
            granted: HashSet::new(),
            local_url: Some(Url::parse("tauri://localhost/index.html").unwrap()),
        }
    }

    #[test]
    fn navigation_guard() {
        let s = shared(Some("http://192.168.0.50:8765"));
        let ok = |u: &str| navigation_allowed(&s, &Url::parse(u).unwrap());
        assert!(ok("tauri://localhost/index.html?trocar=1"));
        assert!(ok("http://tauri.localhost/index.html"));
        assert!(ok("http://192.168.0.50:8765/"));
        assert!(ok("http://192.168.0.50:8765/entrada?x=1"));
        assert!(!ok("http://192.168.0.50:9999/"));
        assert!(!ok("https://192.168.0.50:8765/"));
        assert!(!ok("https://example.com/"));
        let none = shared(None);
        assert!(!navigation_allowed(&none, &Url::parse("http://192.168.0.50:8765/").unwrap()));
    }
}
