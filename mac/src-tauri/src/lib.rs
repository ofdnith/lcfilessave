#[tauri::command]
fn get_server_url(state: tauri::State<'_, AppState>) -> Option<String> {
    state.server_url()
}

#[tauri::command]
fn set_server_url(
    app: AppHandle,
    state: tauri::State<'_, AppState>,
    url: String,
) -> Result<String, String> {
    let origin = config::normalize_server_url(&url)?;
    let path = state.shared.lock().unwrap().config_path.clone();
    config::save(&path, &config::AppConfig { server_url: Some(origin.clone()) })?;
    state.shared.lock().unwrap().server_url = Some(origin.clone());
    grant_remote(&app, &state, &origin)?;
    Ok(origin)
}

#[derive(Serialize)]
struct ServerCheck {
    url: String,
    status: String,
    version: Option<String>,
    problems: Vec<String>,
}

/// GET <url>/api/health from Rust (no CORS involved).
#[tauri::command]
async fn test_server(state: tauri::State<'_, AppState>, url: String) -> Result<ServerCheck, String> {
    let origin = config::normalize_server_url(&url)?;
    let resp = state
        .http
        .get(format!("{origin}/api/health"))
        .timeout(Duration::from_secs(5))
        .send()
        .await
        .map_err(|e| {
            if e.is_timeout() {
                format!("{origin} não respondeu a tempo. O servidor está ligado e na mesma rede (ou no Tailscale)?")
            } else if e.is_connect() {
                format!("Não consegui conectar a {origin}. Confira o endereço e se o servidor está ligado.")
            } else {
                format!("Falha ao falar com {origin}: {e}")
            }
        })?;
    let code = resp.status();
    let body: serde_json::Value = resp
        .json()
        .await
        .map_err(|_| format!("{origin} respondeu, mas não parece ser um servidor Acervo."))?;
    let status = body.get("status").and_then(|v| v.as_str()).map(str::to_string);
    let Some(status) = status else {
        return Err(format!(
            "{origin} respondeu (HTTP {}), mas não parece ser um servidor Acervo.",
            code.as_u16()
        ));
    };
    Ok(ServerCheck {
        url: origin,
        status,
        version: body.get("version").and_then(|v| v.as_str()).map(str::to_string),
        problems: body
            .get("problems")
            .and_then(|v| v.as_array())
            .map(|a| a.iter().filter_map(|p| p.as_str().map(str::to_string)).collect())
            .unwrap_or_default(),
    })
}

