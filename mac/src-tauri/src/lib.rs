#[tauri::command]
async fn pick_folder(app: AppHandle) -> Result<Option<String>, String> {
    let (tx, rx) = tokio::sync::oneshot::channel();
    app.dialog()
        .file()
        .set_title("Escolha a pasta para enviar ao Acervo")
        .pick_folder(move |p| {
            let _ = tx.send(p);
        });
    let picked = rx.await.map_err(|_| "A janela de escolha foi fechada.".to_string())?;
    Ok(picked
        .and_then(|fp| fp.into_path().ok())
        .map(|p| p.to_string_lossy().into_owned()))
}

#[tauri::command]
async fn scan_folder(path: String) -> Result<Vec<ScannedFile>, String> {
    blocking(move || transfer::scan_folder(Path::new(&path))).await?
}

#[tauri::command]
async fn hash_file(path: String) -> Result<String, String> {
    transfer::sha256_file_async(PathBuf::from(&path))
        .await
        .map_err(|e| format!("Não consegui ler {path}: {e}"))
}

#[allow(clippy::too_many_arguments)]
#[tauri::command]
async fn upload_file(
    state: tauri::State<'_, AppState>,
    server_url: String,
    token: Option<String>,
    path: String,
    source: Option<String>,
    session_id: Option<i64>,
    sha256: Option<String>,
    created_ms: Option<i64>,
    client_key: Option<String>,
) -> Result<serde_json::Value, String> {
    let server = state.require_server(&server_url)?;
    upload::upload_file(
        &state.http,
        upload::UploadParams {
            server_url: &server,
            token: token.as_deref(),
            path: Path::new(&path),
            source: source.as_deref().unwrap_or("mac"),
            session_id,
            sha256: sha256.as_deref(),
            created_ms,
            client_key: client_key.as_deref(),
        },
    )
    .await
}

