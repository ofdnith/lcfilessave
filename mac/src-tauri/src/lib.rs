async fn blocking<T: Send + 'static>(f: impl FnOnce() -> T + Send + 'static) -> Result<T, String> {
    tokio::task::spawn_blocking(f)
        .await
        .map_err(|e| format!("Erro interno: {e}"))
}

/// The disk must be plugged in right now; returns its mount path.
fn plugged_disk(mount_path: &str) -> Result<disks::Disk, String> {
    disks::find_disk(mount_path)
        .ok_or_else(|| format!("O disco {mount_path} não está conectado."))
}

fn writable_disk(mount_path: &str) -> Result<disks::Disk, String> {
    let d = plugged_disk(mount_path)?;
    if d.read_only {
        return Err(format!("O disco {} está montado só para leitura.", d.label));
    }
    Ok(d)
}

#[tauri::command]
async fn list_disks() -> Result<Vec<disks::Disk>, String> {
    blocking(disks::list_disks).await
}

#[tauri::command]
async fn init_volume(
    mount_path: String,
    id: String,
    name: String,
    created_at: String,
) -> Result<disks::VolumeJson, String> {
    blocking(move || {
        let d = writable_disk(&mount_path)?;
        disks::init_volume_at(Path::new(&d.mount_path), &d.filesystem, &id, &name, &created_at)
    })
    .await?
}

#[derive(Clone, Serialize)]
struct CopyProgress<'a> {
    rel_path: &'a str,
    bytes_done: u64,
    bytes_total: u64,
}

#[allow(clippy::too_many_arguments)]
#[tauri::command]
async fn copy_to_volume(
    app: AppHandle,
    state: tauri::State<'_, AppState>,
    server_url: String,
    token: Option<String>,
    mount_path: String,
    url: String,
    rel_path: String,
    sha256: String,
    size_bytes: Option<u64>,
) -> Result<CopyResult, String> {
    let server = state.require_server(&server_url)?;
    let mp = mount_path.clone();
    let disk = blocking(move || writable_disk(&mp)).await??;
    let rp = rel_path.clone();
    transfer::copy_to_volume(
        &state.http,
        &server,
        token.as_deref(),
        Path::new(&disk.mount_path),
        &url,
        &rel_path,
        &sha256,
        size_bytes,
        move |done, total| {
            let _ = app.emit(
                "copy-progress",
                CopyProgress { rel_path: &rp, bytes_done: done, bytes_total: total },
            );
        },
    )
    .await
}

#[tauri::command]
async fn write_bundle_file(
    state: tauri::State<'_, AppState>,
    server_url: String,
    token: Option<String>,
    mount_path: String,
    path: String,
    url: String,
) -> Result<(), String> {
    let server = state.require_server(&server_url)?;
    let disk = blocking(move || writable_disk(&mount_path)).await??;
    transfer::write_bundle_file(
        &state.http,
        &server,
        token.as_deref(),
        Path::new(&disk.mount_path),
        &path,
        &url,
    )
    .await
}

#[tauri::command]
async fn verify_volume_files(
    mount_path: String,
    files: Vec<VerifyFile>,
) -> Result<Vec<VerifyResult>, String> {
    blocking(move || {
        let d = plugged_disk(&mount_path)?;
        let mount = PathBuf::from(&d.mount_path);
        Ok(files.iter().map(|f| transfer::verify_one(&mount, f)).collect())
    })
    .await?
}

#[tauri::command]
async fn open_on_volume(app: AppHandle, mount_path: String, rel_path: String) -> Result<(), String> {
    let path = blocking(move || -> Result<PathBuf, String> {
        let d = plugged_disk(&mount_path)?;
        let p = transfer::safe_join(Path::new(&d.mount_path), &rel_path)?;
        if !p.is_file() {
            return Err(format!("Arquivo não encontrado no disco: {rel_path}"));
        }
        Ok(p)
    })
    .await??;
    app.opener()
        .open_path(path.to_string_lossy(), None::<&str>)
        .map_err(|e| format!("Não consegui abrir o arquivo: {e}"))
}

