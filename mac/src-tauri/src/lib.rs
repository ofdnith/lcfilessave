//! Acervo for macOS.
//!
//! The main window shows the Acervo web UI **loaded from the user's own server**
//! (so login cookies are same-origin and the UI is not duplicated). The UI
//! detects `window.__TAURI__` and calls the native commands below for what only
//! the Mac can do: disks, volumes, verified copies, local folders.
//!
//! A tiny bundled page (`src/index.html`) asks for the server address when none
//! is configured, when it is unreachable, or when the user picks
//! "Trocar servidor…" in the menu.
//!
//! Nothing runs in the background: no tray, no daemon. Work happens only while
//! the window is open (spec: "só enquanto o app está aberto").

