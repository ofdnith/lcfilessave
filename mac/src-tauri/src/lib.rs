fn build_menu(app: &AppHandle) -> tauri::Result<Menu<tauri::Wry>> {
    let change = MenuItem::with_id(app, MENU_CHANGE_SERVER, "Trocar servidor…", true, None::<&str>)?;
    let reload = MenuItem::with_id(app, MENU_RELOAD, "Recarregar", true, Some("CmdOrCtrl+R"))?;
    let app_menu = Submenu::with_items(
        app,
        "Acervo",
        true,
        &[
            &PredefinedMenuItem::about(app, Some("Sobre o Acervo"), None)?,
            &PredefinedMenuItem::separator(app)?,
            &change,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::hide(app, Some("Ocultar Acervo"))?,
            &PredefinedMenuItem::hide_others(app, Some("Ocultar outros"))?,
            &PredefinedMenuItem::show_all(app, Some("Mostrar todos"))?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::quit(app, Some("Sair do Acervo"))?,
        ],
    )?;
    // The Edit menu is what makes ⌘C/⌘V/⌘A work inside a macOS webview.
    let edit = Submenu::with_items(
        app,
        "Editar",
        true,
        &[
            &PredefinedMenuItem::undo(app, Some("Desfazer"))?,
            &PredefinedMenuItem::redo(app, Some("Refazer"))?,
            &PredefinedMenuItem::separator(app)?,
            &PredefinedMenuItem::cut(app, Some("Recortar"))?,
            &PredefinedMenuItem::copy(app, Some("Copiar"))?,
            &PredefinedMenuItem::paste(app, Some("Colar"))?,
            &PredefinedMenuItem::select_all(app, Some("Selecionar tudo"))?,
        ],
    )?;
    let view = Submenu::with_items(
        app,
        "Visualizar",
        true,
        &[&reload, &PredefinedMenuItem::fullscreen(app, Some("Tela cheia"))?],
    )?;
    let window = Submenu::with_items(
        app,
        "Janela",
        true,
        &[
            &PredefinedMenuItem::minimize(app, Some("Minimizar"))?,
            &PredefinedMenuItem::close_window(app, Some("Fechar janela"))?,
        ],
    )?;
    Menu::with_items(app, &[&app_menu, &edit, &view, &window])
}

